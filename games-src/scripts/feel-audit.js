// Feel audit: turns BRIEF-GAMEFEEL.md points 3-5 into numbers for ONE game (or all of them).
//   node games-src/scripts/feel-audit.js <slug> [--secs 180] [--sizes phone,pc] [--modes learn,play]
//   node games-src/scripts/feel-audit.js --all [--jobs 3] [--secs 180]    (every slug in build-all.py except deep-signal)
//   node games-src/scripts/feel-audit.js --summary                         (rewrites games-src/qa/feel/SUMMARY.md from the json files)
// For each size (phone 390x844 touch, pc 1440x900 mouse) it plays Learn to play, then Play (Hints off, fresh storage), --secs each,
// driving the game like qa-bot.js (taps at the tutor spotlight, then a UI-only random bot), and measures:
//   (a) every toast / bubble / banner / pop-up: visible time vs the rule (until tapped, or >= 4 s + 1 s per 10 words); two at once
//   (b) any message / bubble / tooltip in Play mode with Hints off (should be none)
//   (c) visible text lines over 12 words        (d) text under 14 px on phone        (e) overlapping text boxes after 10 turns
// Output games-src/qa/feel/<slug>.json + one "PASS|FAIL|N/A <slug> (x) ..." line per check. Exit code is 1 when any check FAILs, but only
// with --gate. The page is the deployed games/<slug>/index.html served by gx-serve.js. Sampling resolution is 250 ms (see TICK).
const fs = require('fs'), path = require('path'), cp = require('child_process');
const ROOT = path.resolve(__dirname, '..', '..'), OUT = path.join(ROOT, 'games-src', 'qa', 'feel');
const arg = (n, d) => { const i = process.argv.indexOf('--' + n); return i > 0 ? process.argv[i + 1] : d; };
const has = n => process.argv.includes('--' + n);
const SECS = +arg('secs', 180), TICK = 250;
const sleep = ms => new Promise(r => setTimeout(r, ms));

function slugs() {
  const t = fs.readFileSync(path.join(__dirname, 'build-all.py'), 'utf8');
  const blk = t.slice(t.indexOf('GAMES = {'), t.indexOf('\n}', t.indexOf('GAMES = {')));
  return [...blk.matchAll(/^\s*"([a-z0-9-]+)":\s*\(/gm)].map(m => m[1]).filter(s => s !== 'deep-signal');
}
const CHECKS = ['a', 'b', 'c', 'd', 'e'];
const TITLES = { a: 'messages stay long enough, one at a time', b: 'no messages in Play (hints off)', c: 'no line over 12 words', d: 'no text under 14px (phone)', e: 'no overlapping text after 10 turns' };

// ------------------------------------------------------------------ summary mode
function summary() {
  const fs_ = fs.readdirSync(OUT).filter(f => f.endsWith('.json')).sort();
  const rows = fs_.map(f => JSON.parse(fs.readFileSync(path.join(OUT, f), 'utf8')));
  const mark = r => r ? (r.status === 'PASS' ? 'PASS' : r.status === 'FAIL' ? 'FAIL ' + r.count : 'n/a') : '-';
  let md = '# Feel audit (BRIEF-GAMEFEEL points 3-5)\n\nGenerated by `games-src/scripts/feel-audit.js --summary`. Table cell = PASS, `FAIL <count of findings>`, or n/a (not measurable, e.g. fewer than 10 turns reached). Per-game detail: `qa/feel/<slug>.json`.\n\n';
  md += '| game | ' + CHECKS.map(c => `(${c})`).join(' | ') + ' | secs/session | notes |\n|---|' + CHECKS.map(() => '---').join('|') + '|---|---|\n';
  for (const j of rows) md += `| ${j.slug} | ${CHECKS.map(c => mark(j.checks[c])).join(' | ')} | ${j.secs} | ${(j.notes || []).join('; ').replace(/\|/g, '/').slice(0, 140)} |\n`;
  const tot = c => rows.filter(j => j.checks[c] && j.checks[c].status === 'FAIL').length;
  md += `\n**FAIL counts (games):** ${CHECKS.map(c => `(${c}) ${tot(c)}/${rows.length}`).join(', ')}\n\nChecks: ` + CHECKS.map(c => `(${c}) ${TITLES[c]}`).join('; ') + '.\n';
  fs.writeFileSync(path.join(OUT, 'SUMMARY.md'), md);
  console.log(md);
}

// ------------------------------------------------------------------ all mode
async function all() {
  const list = slugs(), jobs = +arg('jobs', 3); let i = 0;
  const extra = process.argv.slice(2).filter((a, k, v) => a !== '--all' && !(a === '--jobs' || v[k - 1] === '--jobs'));
  const worker = async () => {
    while (i < list.length) {
      const s = list[i++];
      await new Promise(res => { const p = cp.spawn('node', [__filename, s, ...extra], { stdio: ['ignore', 'pipe', 'pipe'] }); let o = ''; p.stdout.on('data', d => o += d); p.stderr.on('data', d => o += d);
        const t = setTimeout(() => p.kill('SIGKILL'), (SECS * 4 + 240) * 1000);
        p.on('close', () => { clearTimeout(t); process.stdout.write(o.split('\n').filter(l => /^(PASS|FAIL|N\/A|FATAL)/.test(l)).join('\n') + '\n'); res(); }); });
    }
  };
  await Promise.all(Array.from({ length: jobs }, worker));
  summary();
}

