#!/usr/bin/env python3
"""Cost guard: stops the things that made workers read 300-650k tokens per session. Run by build-all.py
(fails the build) and by .github/workflows/guard.yml on every push to the work branch.

  python3 games-src/scripts/guard.py                  # check, exit 1 on any failure
  python3 games-src/scripts/guard.py --update-baseline   # accept the current state (lowers sizes, records new files); commit the json

Checks (each failure prints a one-line fix):
  (a) a tracked file under games-src/ over 400 KB that is not media/audio/models/vendor/fonts
  (b) a source file that was already over 120 KB grows (baseline: games-src/guard-baseline.json)
  (c) a game gains a NEW override layer file (ui14.js style numbered file, or a new file that re-defines functions of an earlier one)
  (d) a built artefact (game html, x.js, joined ui.js, kit demo.html) is tracked in git again
"""
import importlib.util, json, pathlib, re, subprocess, sys

HERE = pathlib.Path(__file__).resolve().parent
SRC = HERE.parent
REPO = SRC.parent
BASELINE = SRC / "guard-baseline.json"
BIG = 400 * 1024
GROW = 120 * 1024
MEDIA_EXT = {".mp3", ".mp4", ".glb", ".gltf", ".png", ".jpg", ".jpeg", ".webp", ".ogg", ".wav", ".woff", ".woff2", ".ttf", ".otf", ".gif", ".webm", ".ico", ".svg", ".bin", ".ktx2", ".hdr"}
MEDIA_DIRS = {"audio", "media", "models", "vendor", "fonts", "anims", "facelift-3d", "art", "covers", "node_modules"}
RESEARCH_DIRS = {"playtest", "analysis", "shots", "audit-shots", "licence-snapshots", "next-wave", "asset-viewer", "room", "sweep-shots", "board-first-shots", "phone-check-shots"}
CODE_EXT = {".js", ".css", ".html", ".py", ".sh"}
NUMBERED_LAYER = re.compile(r"^[A-Za-z]+\d+\.js$")


def load(name, path):
    spec = importlib.util.spec_from_file_location(name, path)
    m = importlib.util.module_from_spec(spec); spec.loader.exec_module(m)
    return m


def tracked():
    out = subprocess.run(["git", "ls-files", "-z", "--", "games-src"], cwd=REPO, capture_output=True, text=True, check=True).stdout
    return [p for p in out.split("\0") if p and (REPO / p).exists()]


def is_media(rel):
    p = pathlib.Path(rel)
    return p.suffix.lower() in MEDIA_EXT or bool(MEDIA_DIRS & set(p.parts)) or p.name == "audio-data.js"


def source_files(files):
    for rel in files:
        p = pathlib.Path(rel)
        if is_media(rel) or RESEARCH_DIRS & set(p.parts) or p.suffix not in CODE_EXT: continue
        yield rel


def artefacts(modmap, build_all):
    """Repo-relative paths that must never be tracked."""
    out = {}
    for slug, (d, cmd, o) in build_all.GAMES.items():
        out[str(pathlib.Path("games-src", d, o).resolve().relative_to(REPO))] = slug
    for slug in modmap.GAMES:
        a = modmap.analyse(slug)
        for g in a["generated"]:
            if "joined" in g: out["games-src/" + g.split(" ")[0]] = slug
    for p in ("short-fuse/game/debug.html", "hollowbough/kit/demo.html", "kaiten/kit/demo.html", "short-fuse/kit/demo.html", "thornbound/kit/demo.html", "tidewake/kit/demo.html"):
        out["games-src/" + p] = "kit/debug build"
    return out


def snapshot(modmap, files):
    sizes = {rel: (REPO / rel).stat().st_size for rel in source_files(files) if (REPO / rel).stat().st_size > GROW}
    layers = {}
    for slug in modmap.GAMES:
        a = modmap.analyse(slug)
        layers[slug] = [f["path"] for f in a["files"] if not f["shared"]]
    return {"_note": "generated by games-src/scripts/guard.py --update-baseline; sizes in bytes of source files over 120 KB (they must not grow), layers = each game's own files in build order",
            "sizes": dict(sorted(sizes.items())), "layers": layers}


def main(argv):
    modmap = load("modmap", HERE / "modmap.py")
    build_all = load("build_all", HERE / "build-all.py")
    files = tracked()
    if "--update-baseline" in argv:
        BASELINE.write_text(json.dumps(snapshot(modmap, files), indent=1) + "\n")
        print("guard: baseline written (%d big sources, %d games)" % (len(json.loads(BASELINE.read_text())["sizes"]), len(modmap.GAMES)))
        return 0
    base = json.loads(BASELINE.read_text()) if BASELINE.exists() else {"sizes": {}, "layers": {}}
    fails, notes = [], []

    # (a) big non-media tracked files
    for rel in files:
        if is_media(rel): continue
        sz = (REPO / rel).stat().st_size
        if sz > BIG:
            fails.append("(a) %s is %d KB (> 400 KB) and is not media. Fix: if it is generated, git rm --cached it and add it to games-src/.gitignore; if it is data, split it or move it into audio/media/ or vendor/." % (rel, sz // 1024))

    # (b) big source files must not grow
    for rel in source_files(files):
        sz = (REPO / rel).stat().st_size
        if sz <= GROW: continue
        old = base["sizes"].get(rel)
        if old is None:
            fails.append("(b) %s is %d KB, over 120 KB and not in the baseline. Fix: split it, or put the new code in a small file that owns it; the baseline is only updated by the orchestrator (guard.py --update-baseline)." % (rel, sz // 1024))
        elif sz > old:
            fails.append("(b) %s grew %d -> %d bytes (a source over 120 KB may not grow). Fix: put new code in a smaller file/module, or shrink this one in the same commit." % (rel, old, sz))
        elif sz < old - 2048:
            notes.append("note: %s shrank to %d KB; run guard.py --update-baseline to ratchet the limit down" % (rel, sz // 1024))

    # (c) no new override layer files
    missing = [s for s in build_all.GAMES if s not in modmap.GAMES]
    if missing:
        fails.append("(c) game(s) %s are in build-all.py but not in modmap.py GAMES. Fix: add them to modmap.GAMES so their code map and layer check exist." % ", ".join(missing))
    all_orders = set()
    for slug in modmap.GAMES:
        a = modmap.analyse(slug)
        old = base["layers"].get(slug)
        for f in a["files"]:
            all_orders.add("games-src/" + f["path"])
        if old is None:
            notes.append("note: %s has no layer baseline yet (new game); run guard.py --update-baseline" % slug)
            continue
        for f in a["files"]:
            if f["shared"] or f["path"] in old: continue
            ov = a["per_file"].get(f["idx"], {})
            syms = sorted({s for v in ov.values() for s in v})
            if NUMBERED_LAYER.match(f["name"]) or syms:
                why = ("re-defines " + ", ".join(syms[:5])) if syms else "is a numbered layer file"
                fails.append("(c) %s: new override layer %s %s. Fix: put the change in the file that owns the function (games-src/scripts/find.sh %s %s), do not add a layer file." % (slug, f["path"], why, syms[0] if syms else "<function>", slug))
    gdirs = set()
    for slug in modmap.GAMES:
        bd = modmap.GAMES[slug][1]
        gdirs |= {"games-src/" + bd, "games-src/" + bd + "/src"}
    for rel in files:
        p = pathlib.Path(rel)
        if re.fullmatch(r"ui\d+\.js", p.name) and p.parent.as_posix() in gdirs and rel not in all_orders:
            fails.append("(c) %s is a numbered ui file the build does not use (silently ignored, or a new layer). Fix: edit the file that owns the function instead." % rel)

    # (d) built artefacts must stay untracked
    art = artefacts(modmap, build_all)
    tr = set(files)
    for rel, who in sorted(art.items()):
        if rel in tr:
            fails.append("(d) %s is a build output (%s) and is tracked again. Fix: git rm --cached %s (keep the file on disk); it is in games-src/.gitignore." % (rel, who, rel))
    for rel in files:
        if pathlib.Path(rel).name == "x.js" and rel in tr:
            fails.append("(d) %s is the build's script dump and is tracked. Fix: git rm --cached %s." % (rel, rel))

    for n in notes: print(n)
    if fails:
        print("GUARD FAILED (%d):" % len(fails))
        for f in fails: print("  " + f)
        return 1
    print("guard: ok (%d tracked files under games-src, %d big sources, %d games checked)" % (len(files), len(base["sizes"]), len(modmap.GAMES)))
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
