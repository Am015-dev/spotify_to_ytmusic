# Writes src/icons.js from a local clone of game-icons.net (CC BY 3.0; authors credited in ASSETS.md and THIRD-PARTY.md).
# usage: python3 tools/icons.py <path-to-game-icons-clone>
import sys, re, json, os
MAP = {'brick': 'delapouite/brick-pile', 'food': 'lorc/wheat', 'tool': 'lorc/hammer-nails', 'wine': 'lorc/grapes', 'cloth': 'delapouite/rolled-cloth',
       'hearth': 'sbed/fire', 'eagle': 'lorc/eagle-emblem', 'sickle': 'delapouite/sickle', 'wing': 'delapouite/caduceus', 'shield': 'delapouite/roman-shield', 'owl': 'lorc/owl',
       'temple': 'delapouite/greek-temple', 'scroll': 'lorc/scroll-unfurled', 'coins2': 'delapouite/two-coins', 'laurel': 'lorc/laurel-crown', 'toga': 'delapouite/roman-toga',
       'masks': 'lorc/drama-masks', 'meeple': 'delapouite/meeple', 'bugle': 'lorc/bugle-call', 'trowel': 'delapouite/trowel', 'ship': 'delapouite/trireme', 'house': 'delapouite/house',
       'coins': 'delapouite/coins', 'amphora': 'delapouite/amphora', 'crown': 'lorc/crown', 'gate': 'delapouite/temple-gate'}
out = {}
for k, p in MAP.items():
    s = open(os.path.join(sys.argv[1], p + '.svg'), encoding='utf-8').read()
    ds = [d for d in re.findall(r'<path[^>]*\sd="([^"]+)"', s) if d.strip() != 'M0 0h512v512H0z']
    out[k] = ' '.join(ds)
open(os.path.join(os.path.dirname(__file__), '..', 'src', 'icons.js'), 'w').write('// Icons from game-icons.net (CC BY 3.0: Delapouite, Lorc, Sbed). 512x512 path data. Generated by tools/icons.py.\nwindow.VT_ICONS=' + json.dumps(out, separators=(',', ':')) + ';\n')
print(len(out), 'icons')
