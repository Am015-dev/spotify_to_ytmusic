#!/usr/bin/env python3
"""Generates TEST-LEDGER.md: every test file under games-src/nightrun with its runner status.
RUN = invoked by smoke.sh; BROKEN = listed in test-status.tsv (known red or hanging); NOT RUN = everything else
(root *-test.js are run nightly by test-ledger.sh; qa/ tests and probe scripts have no runner yet)."""
import re, glob, os, sys
H = os.path.dirname(os.path.abspath(__file__))
smoke = open(os.path.join(H, 'smoke.sh')).read()
run = set(re.findall(r'(?:\$HERE/)([\w./-]+\.js)', smoke))
broken = {}
for l in open(os.path.join(H, 'test-status.tsv')):
    if l.startswith('#') or not l.strip(): continue
    f, st, why = (l.rstrip('\n').split('\t') + ['', ''])[:3]
    broken[f] = (st, why)
files = sorted(os.path.relpath(f, H) for pat in ('*-test.js', 'qa/*-test.js') for f in glob.glob(os.path.join(H, pat)))
rows, cnt = [], {'RUN': 0, 'NOT RUN': 0, 'BROKEN': 0}
for f in files:
    if f in broken: st, why = 'BROKEN', broken[f][1]
    elif f in run: st, why = 'RUN', 'smoke.sh'
    elif '/' in f: st, why = 'NOT RUN', 'qa/ test, no runner (run by hand: node games-src/nightrun/' + f + ')'
    else: st, why = 'NOT RUN', 'nightly set: test-ledger.sh'
    cnt[st] += 1; rows.append('| %s | %s | %s |' % (f, st, why.replace('|', '/')))
out = ['# Nightrun test ledger (generated by ledger.py; do not edit)', '',
       'Which test file is run by which runner. RUN = in smoke.sh (each under a hard timeout). BROKEN = known red or hanging, reason in test-status.tsv. NOT RUN = no automatic runner on every change.',
       'Nightly pass/fail results of the root tests: TEST-RESULTS-NIGHTLY.md (test-ledger.sh).', '',
       'Totals: %d test files: %d RUN, %d NOT RUN, %d BROKEN.' % (len(files), cnt['RUN'], cnt['NOT RUN'], cnt['BROKEN']), '',
       '| Test | Runner status | Note |', '|---|---|---|'] + rows
open(os.path.join(H, 'TEST-LEDGER.md'), 'w').write('\n'.join(out) + '\n')
print('Totals: %d files: %d RUN, %d NOT RUN, %d BROKEN' % (len(files), cnt['RUN'], cnt['NOT RUN'], cnt['BROKEN']))
