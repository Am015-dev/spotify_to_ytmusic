#!/usr/bin/env python3
"""Writes ASSET-CHECK.md: every picture id the rules (src/data.js), the code (data-art / art slots) and campaign.json use must have a stem in
assets.json and a Flow prompt in next-wave/flow-2d/wildmark/. Exit 1 when a gap exists.   python3 games-src/wildmark/asset-check.py"""
import json, pathlib, re, subprocess, sys
D = pathlib.Path(__file__).resolve().parent
data = json.loads(subprocess.check_output(["node", "-e", "global.window={};const W=require('./src/data.js');console.log(JSON.stringify({ter:W.TER,ani:W.ANI,tiles:W.TILES,cards:Object.keys(W.CARDS)}))"], cwd=D))
camp = json.load(open(D / "campaign.json"))
stems = {i["stem"]: i for i in json.load(open(D / "assets.json"))["items"]}
prompted = set()
for f in (D.parent / "next-wave" / "flow-2d" / "wildmark").glob("prompts-wave*-ratio-*.json"): prompted |= set(json.load(open(f))["cards"])
req = []   # (group, id, stem)
for t in data["ter"]: req.append(("terrain", t, "ter-" + t))
for a in data["ani"] + ["acorn"]: req.append(("token", a, "tok-" + a))
for a in data["cards"]: req.append(("scoring card (set A, in play)", a, "card-%s-a" % a))
for a in data["cards"]:
    for s in "bcd": req.append(("scoring card (set %s, in play: Mixed + Story act 3)" % s.upper(), a, "card-%s-%s" % (a, s)))
seen = set()
for k, c in camp["cast"].items():
    st = c["portrait"].replace(".webp", ""); req.append(("character", k, st)); seen.add(st)
for ch in camp["chapters"]:
    st = ch["opponent"]["portrait"].replace(".webp", "")
    req.append(("boss" if ch["boss"] else "rival / chapter opponent", ch["id"] + " " + ch["opponent"]["name"], st))
src = "".join(p.read_text() for p in (D / "src").glob("*.*"))
for st in sorted(set(re.findall(r'data-art="([a-z0-9-]+)"', src))): req.append(("board / background / icon (data-art in code)", st, st))
req.append(("board", "terrain patterns on the map", "table-bg"))
for st in ("result-win", "result-lose"): req.append(("background (result screen + Story result)", st, st))
for t in data["tiles"]:   # each habitat tile is drawn from its terrain textures + animal tokens
    for x in t["t"]: req.append(("habitat tile %d (composite)" % t["id"], x, "ter-" + x))
    for a in t["a"]: req.append(("habitat tile %d (composite)" % t["id"], a, "tok-" + a))
rows, gaps, uniq = [], [], {}
for g, i, st in req:
    ok_s, ok_p = st in stems, st in prompted
    if not (ok_s and ok_p): gaps.append((g, i, st, ok_s, ok_p))
    if g.startswith("habitat tile"): continue
    uniq[(g, i)] = (st, ok_s, ok_p)
tiles_ok = all(st in stems and st in prompted for g, i, st in req if g.startswith("habitat tile"))
out = ["# Wildmark asset check (generated by asset-check.py)", "",
       "Required = every picture id the rules, the code and campaign.json use. Stem = in assets.json. Prompted = in a Flow prompt file.", "",
       "| Required | Stem | Prompted | Gaps |", "|---|---|---|---|",
       "| %d ids (+85 habitat tiles as composites) | %d | %d | **%d** |" % (len(uniq), sum(1 for v in uniq.values() if v[1]), sum(1 for v in uniq.values() if v[2]), len(gaps)), "",
       "Habitat tiles: all 85 are drawn from their terrain textures (ter-*) and animal tokens (tok-*): %s." % ("every one covered" if tiles_ok else "GAPS"), "",
       "| Group | Id | Stem | Stem ok | Prompt ok |", "|---|---|---|---|---|"]
for (g, i), (st, a, b) in uniq.items(): out.append("| %s | %s | `%s` | %s | %s |" % (g, i, st, "yes" if a else "NO", "yes" if b else "NO"))
out += ["", "Unused stems (prepared for later): " + (", ".join(sorted(set(stems) - {v[0] for v in uniq.values()})) or "none"), "",
        "Music: one cue per gx-music slot (menu, main, victory, defeat) in `games-src/next-wave/music/wildmark/cues-wave1.json`."]
(D / "ASSET-CHECK.md").write_text("\n".join(out) + "\n")
print("asset-check: %d required, %d gaps" % (len(uniq), len(gaps))); sys.exit(1 if gaps else 0)
