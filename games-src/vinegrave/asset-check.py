#!/usr/bin/env python3
"""Writes ASSET-CHECK.md: every picture id the rules, the UI and campaign.json use must have a stem in assets.json and a Flow prompt.
   python3 games-src/vinegrave/asset-check.py   (exit 1 when gaps > 0)"""
import json, pathlib, re, subprocess, sys
D = pathlib.Path(__file__).resolve().parent; SP = D.parent
V = json.loads(subprocess.check_output(['node', '-e', "const V=require('./src/data.js');console.log(JSON.stringify({c:Object.keys(V.CARDS),s:Object.keys(V.SITE),g:V.GUARDS,i:V.IDOLS,r:V.RES,t:V.TRAVEL}))"], cwd=D))
camp = json.loads((D / 'campaign.json').read_text())
need = []   # (group, stem)
need += [('card', 'card-' + c) for c in V['c']] + [('site', 'site-' + s) for s in V['s']] + [('site', 'site-hidden-1'), ('site', 'site-hidden-2')]
need += [('guardian', 'guard-' + g) for g in V['g']] + [('idol', i) for i in V['i']]
need += [('icon', 'res-' + r) for r in V['r']] + [('icon', 'tr-' + t) for t in V['t']]
need += [('character/boss', 'portrait-' + k) for k in camp['cast']]
# literal data-art stems in the UI source (boards, backgrounds, result screens)
src = ''.join(p.read_text() for p in sorted((D / 'src').glob('*.js'))) + (D / 'src' / 'body.html').read_text()
for m in sorted(set(re.findall(r'data-art="([a-z0-9-]+)"', src))): need.append(('board/background/ui', m))
for m in ('result-win', 'result-lose'): need.append(('board/background/ui', m))
seen = set(); need = [n for n in need if not (n[1] in seen or seen.add(n[1]))]
stems = {i['stem'] for i in json.loads((D / 'assets.json').read_text())['items']}
prompted = set()
for f in (SP / 'next-wave' / 'flow-2d' / 'vinegrave').glob('*.json'): prompted |= set(json.loads(f.read_text())['cards'].keys())
rows, gaps = [], []
groups = {}
for g, s in need:
    st = 'ok' if s in stems and s in prompted else ('no stem' if s not in stems else 'no prompt')
    groups.setdefault(g, [0, 0, 0]); groups[g][0] += 1; groups[g][1] += s in stems; groups[g][2] += s in prompted
    if st != 'ok': gaps.append((g, s, st))
out = ['# Vinegrave asset check', '', 'Generated by `asset-check.py`: every picture id the rules (src/data.js), the UI (data-art in src/) and campaign.json (cast) use.', '',
       '| group | required | have a stem | have a Flow prompt |', '|---|---|---|---|']
for g, (n, a, b) in groups.items(): out.append('| %s | %d | %d | %d |' % (g, n, a, b))
tot = len(need); out += ['| **total** | **%d** | **%d** | **%d** |' % (tot, sum(1 for g, s in need if s in stems), sum(1 for g, s in need if s in prompted)), '',
       '**Gaps: %d**' % len(gaps)] + ['- %s `%s`: %s' % x for x in gaps]
extra = sorted(stems - {s for g, s in need}); out += ['', 'Extra slots (wave-3 polish, not drawn by code yet): ' + ', '.join(extra)]
out += ['', 'Music: one cue per gx-music slot (tavern, main, fight, victory, defeat) in `next-wave/music/vinegrave/cues-wave1.json`.']
(D / 'ASSET-CHECK.md').write_text('\n'.join(out) + '\n')
print('asset-check: required', tot, 'gaps', len(gaps)); sys.exit(1 if gaps else 0)
